// Ritorna t(key, vars): interpola {var} nel template della lingua scelta (fallback IT).
// Interpolazione con forma PLURALE: `{var#singolare#plurale}` scegle in base a vars[var]
// (1 → singolare, altrimenti plurale). Stessa sintassi del client (web/i18n.jsx), così le stringhe
// si spostano da una parte all'altra senza riscriverle. Serve perché un'etichetta che accompagna un
// conteggio ("1 errori") è sbagliata: il numero e la parola devono concordare.
function interpolate(s, vars) {
  s = String(s).replace(/\{(\w+)#([^#{}]*)#([^{}]*)\}/g, (_, k, one, other) => (Number(vars?.[k]) === 1 ? one : other))
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export function makeT(lang) {
  const L = S[lang] ? lang : 'it'
  return (key, vars) => interpolate(S[L][key] ?? S.it[key] ?? key, vars)
}

// t neutro (identità) per quando un check gira senza lingua (es. fuori da una richiesta HTTP).
export const identityT = (key, vars) => interpolate(key, vars)

// Codice di stato AWS → parola leggibile (`state.*`). Una mappa SOLA per tutti i provider: gli stati
// arrivano in grafie diverse a seconda del servizio (`ACTIVE`, `Deployed`, `active_impaired`) e prima
// ognuno faceva da sé — RDS ed EC2 traducevano, DynamoDB/EKS/Kinesis/CloudFront/ElastiCache/ALB no,
// e in mezzo a una frase italiana restava la parola inglese. Codice non mappato → torna grezzo (meglio
// un `ARCHIVING` in inglese che una riga senza lo stato).
export function awsState(code, t = identityT) {
  const raw = String(code ?? '').trim()
  if (!raw) return '—'
  const k = `state.${raw.toLowerCase()}`
  const v = t(k)
  return v === k ? raw : v
}

// Durata compatta "Nu" i18n (bare): da ms di elapsed a "2h"/"12g"/"5m".
function fmtElapsed(ms, t) {
  const min = Math.floor(ms / 60000)
  if (min < 60) return { n: Math.max(1, min), unit: t('time.unit.m') }
  const hours = Math.round(min / 60)
  if (hours < 24) return { n: hours, unit: t('time.unit.h') }
  return { n: Math.round(hours / 24), unit: t('time.unit.d') }
}

// Elapsed bare (senza "fa"/"ago"): "12g"/"2h". Per frasi tipo "su da {dur}".
export function fmtDuration(when, t = identityT) {
  const ms = when instanceof Date ? when.getTime() : new Date(when).getTime()
  if (!Number.isFinite(ms)) return ''
  const e = fmtElapsed(Math.max(0, Date.now() - ms), t)
  return `${e.n}${e.unit}`
}

// "tempo fa" i18n: da una data (Date | ISO | epoch ms) a "2h fa"/"2h ago".
// Sotto il minuto → "adesso"/"just now". Unità tradotta via `t` (chiavi time.*).
export function fmtAgo(when, t = identityT) {
  const ms = when instanceof Date ? when.getTime() : new Date(when).getTime()
  if (!Number.isFinite(ms)) return ''
  const elapsed = Math.max(0, Date.now() - ms)
  if (elapsed < 60000) return t('time.now')
  const e = fmtElapsed(elapsed, t)
  return t('time.ago', { n: e.n, unit: e.unit })
}
